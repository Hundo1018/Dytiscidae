"""Bake the thin-plate tables of `FluidSolver.stall_law = "table"`.

    PYTHONPATH=. .venv/bin/python tools/bake_thin_plate.py write   # dytiscidae/physics/thin_plate_tables.py
    PYTHONPATH=. .venv/bin/python tools/bake_thin_plate.py check   # exit 1 if the module is not what the csv give

Two anchors, both UIUC two-dimensional measurements held in
`experiments/flapper/sections/` (`SOURCES.md`): the flat plate (lift runs
only) and Goe 417a (`SectionPolar("goe417a+lift+extend")`, pass W8).  Each is
resampled on one uniform grid of angles at `RE_NODES`, so the numpy solver,
the Mojo kernel and the device path read the same numbers.  The law itself is
`fluid.table_coefficients`; its design and checks are
`experiments/physics_extremes/PREREG_R3_table.md`.
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "dytiscidae" / "physics" / "thin_plate_tables.py"

ALPHA0_DEG, STEP_DEG, N_ALPHA = -25.0, 0.25, 221        # to SectionPolar.PLATE_BY
RE_NODES = (6.0e4, 8.0e4, 1.0e5, 1.2e5, 2.0e5)
FLAT, ARC = "flatplate_uiuc", "goe417a"


def _sections():
    sys.path.insert(0, str(ROOT / "experiments" / "flapper"))
    import sections
    return sections


def camber_of(points) -> float:
    """Largest height of the mean line over the chord, from a section's
    digitised outline."""
    x = points[:, 0]
    i = int(np.argmin(x))
    upper, lower = points[: i + 1][::-1], points[i:]
    xs = np.linspace(0.02, 0.98, 97)
    return float(np.max(0.5 * (np.interp(xs, upper[:, 0], upper[:, 1])
                               + np.interp(xs, lower[:, 0], lower[:, 1]))))


def flat_runs(sections):
    """The flat plate's lift runs made odd: the angle shifted to the measured
    zero-lift angle (a symmetric plate lifts nothing at zero incidence; the
    runs read -0.014 to -0.037 there), the positive side kept."""
    out = []
    for re_, a, cl in sorted(sections.lift_runs(FLAT), key=lambda r: r[0]):
        k = int(np.argmax(cl > 0.0))
        a0 = a[k - 1] - cl[k - 1] * (a[k] - a[k - 1]) / (cl[k] - cl[k - 1])
        a, cl = a[k:] - a0, cl[k:]
        out.append((re_, np.concatenate([[0.0], a]), np.concatenate([[0.0], cl])))
    return out


def build():
    """``dict`` of the module's arrays: `CL`, `CD` of shape (2, n_re,
    n_alpha), `LO`, `TOP` of shape (2, n_re) in radians, `CAMBER`."""
    from dytiscidae.physics.fluid import SectionPolar, skin_friction_cd
    sections = _sections()
    grid = np.radians(ALPHA0_DEG + STEP_DEG * np.arange(N_ALPHA))
    nodes = np.asarray(RE_NODES)
    cl = np.zeros((2, len(nodes), N_ALPHA))
    cd = np.zeros_like(cl)
    lo = np.zeros((2, len(nodes)))
    top = np.zeros_like(lo)

    runs = flat_runs(sections)
    logre = np.log([r for r, _, _ in runs])
    for j, re_ in enumerate(nodes):
        x = float(np.clip(np.log(re_), logre[0], logre[-1]))
        i = int(np.clip(np.searchsorted(logre, x) - 1, 0, len(runs) - 2))
        t = (x - logre[i]) / (logre[i + 1] - logre[i])
        end = (1.0 - t) * runs[i][1][-1] + t * runs[i + 1][1][-1]
        a = np.abs(grid)
        half = (1.0 - t) * np.interp(a, runs[i][1], runs[i][2]) + t * np.interp(a, runs[i + 1][1], runs[i + 1][2])
        cl[0, j] = np.sign(grid) * half
        # no measured drag: the pressure force normal to the chord (past the
        # run's end the lift is held and the drag it implies goes on, as for
        # a `SectionPolar`)
        cd[0, j] = skin_friction_cd(np.array([re_]))[0] + half * np.tan(a)
        lo[0, j], top[0, j] = -end, end

    arc = sections.load(ARC + "+lift+extend")
    assert isinstance(arc, SectionPolar)
    for j, re_ in enumerate(nodes):
        one = np.array([re_])
        lo[1, j] = arc._at(np.zeros(1), one)[2][0]
        top[1, j] = arc._lift_at(np.zeros(1), one)[1][0]
        a = np.maximum(grid, lo[1, j])
        cl[1, j], cd[1, j], _ = arc.table_part(a, np.full(N_ALPHA, re_))
    return dict(CL=cl, CD=cd, LO=lo, TOP=top, CAMBER=camber_of(sections.coordinates(ARC)))


def _block(name, arr):
    rows = [", ".join(f"{v:.6f}" for v in row) for row in arr.reshape(-1, arr.shape[-1])]
    body = ",\n".join(f"    [{r}]" for r in rows)
    return f"{name} = np.array([\n{body},\n]).reshape({arr.shape!r})\n"


def render(t) -> str:
    return (
        '"""Generated by tools/bake_thin_plate.py from experiments/flapper/sections/*.csv.\n'
        "Do not edit: `bake_thin_plate.py write`.\n\n"
        "Static two-dimensional lift and drag of the two thin sections the default\n"
        "law reads (`fluid.table_coefficients`): index 0 the UIUC flat plate, index 1\n"
        "Goe 417a, at `RE_NODES`, on a uniform grid of angles towards the convex side\n"
        "from `ALPHA0` in steps of `STEP` (radians).  `LO`, `TOP`: the measured range\n"
        'of each row.  Below `LO` a row is held; above `TOP` it carries the lift held\nand the drag that lift implies normal to the chord, to 30 deg.\n"""\n'
        "import numpy as np\n\n"
        f"#: Camber of the Goe 417a tunnel model, from its digitised outline.\n"
        f"CAMBER = {t['CAMBER']:.6f}\n"
        f"ALPHA0 = {np.radians(ALPHA0_DEG)!r}\n"
        f"STEP = {np.radians(STEP_DEG)!r}\n"
        f"RE_NODES = np.array({list(RE_NODES)!r})\n\n"
        + _block("CL", t["CL"]) + "\n" + _block("CD", t["CD"]) + "\n"
        + _block("LO", t["LO"]) + "\n" + _block("TOP", t["TOP"])
    )


def main(argv) -> int:
    text = render(build())
    if argv[1:] == ["write"]:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    if argv[1:] == ["check"]:
        ok = OUT.exists() and OUT.read_text() == text
        print("thin-plate tables match the csv" if ok else "thin-plate tables are stale: bake_thin_plate.py write")
        return 0 if ok else 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
